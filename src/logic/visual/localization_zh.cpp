// Exact match only, so a string the table does not list keeps its English text.
extern "C" const char *slinky_translate(const char *text) {
    if (!text || !text[0]) return 0;
    for (int i = 0; i < kTableCount; i++) {
        const char *a = kTable[i].english;
        const char *b = text;
        while (*a && *a == *b) { a++; b++; }
        if (!*a && !*b) return kTable[i].chinese;
    }
    return 0;
}

extern "C" int slinky_translation_count(void) { return kTableCount; }
